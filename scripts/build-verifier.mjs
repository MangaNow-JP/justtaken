import { build } from 'esbuild';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const bundles = await Promise.all(
  ['verifier', 'hash-worker'].map(async (name) => {
    const result = await build({
      absWorkingDir: root,
      entryPoints: [`workers/api/web/${name}.ts`],
      bundle: true,
      write: false,
      minify: true,
      platform: 'browser',
      target: ['es2022'],
      format: 'iife',
      legalComments: 'none',
    });
    return result.outputFiles[0].text;
  }),
);
await mkdir(root + 'workers/api/src/generated', { recursive: true });
await writeFile(
  root + 'workers/api/src/generated/verifier.ts',
  '// Generated by scripts/build-verifier.mjs.\nexport const verifierJS = ' +
    JSON.stringify(bundles[0]) +
    ';\nexport const hashWorkerJS = ' +
    JSON.stringify(bundles[1]) +
    ';\n',
);
console.log('Built standalone verifier and streaming hash worker.');
